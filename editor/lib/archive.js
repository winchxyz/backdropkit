// The theme archive's text, shared by engine/pack.mjs (the site's archives) and the editor's
// exporter (export.js): theme.js, the README, plugin.json and marketplace.json, the slug
// stamped into register.tsx, and the list of entries in the order the archive holds them.
// Plain ES module with no dependencies: it runs in the browser and in Node.
//
// Two flavours, `by`:
//   'packer': the site's themes, made by the BackdropKit community project. Byte for byte what
//             engine/pack.mjs wrote before this file existed.
//   'editor': a theme someone made with the BackdropKit editor; the archive carries its
//             project.json, which the editor opens again.

export const REPO = 'https://github.com/winchxyz/backdropkit'
export const VERSION = '0.1.0'
// Which moment's still is the preview: the first of these the theme has.
export const HERO_ORDER = ['day', 'morning', 'b', 'sunrise', 'sunset', 'golden', 'evening', 'dawn', 'a', 'dusk', 'twilight', 'night']

export const creditOf = (by, repo = REPO) =>
  by === 'editor' ? `Made with the BackdropKit editor (${repo}). Not made by Anthropic.` : `Made by the BackdropKit community project (${repo}). Not made by Anthropic.`
const authorOf = by => (by === 'editor' ? 'BackdropKit editor' : 'BackdropKit community project')

export const clock = hour => {
  const t = Math.round(hour * 60) % 1440
  return String(Math.floor(t / 60)).padStart(2, '0') + ':' + String(t % 60).padStart(2, '0')
}

export function heroOf(moments, order = HERO_ORDER) {
  for (const id of order) {
    const m = moments.find(x => x.id === id)
    if (m) return m
  }
  return moments[0]
}

// What each hooks file is, for the README.
const HOOK_NOTES = {
  'register.tsx': s => `sets the theme when a session starts, picks the scene for the time of day, and adds /${s}-off, /${s}-on and /${s}-time`,
  'register.test.tsx': () => 'tests for register.tsx (claude plugin test mod)',
  'theme.js': () => "the theme: its moments, the hour each starts, the panels' tone and glass over each, and each scene as one animated SVG string",
  'colors.js': () => 'the colours of the light and the dark look, and the blur of the frosted glass',
  'make-colors.js': () => "Anthropic's colour helper, copied from Claude Code's plugin-authoring skill",
  'hooks.json': () => 'names register.tsx as the module to load',
}

// theme.js. moments: [{ id, name, start, tone, tint, opacity, alt, text }], in start order.
export function themeJs(theme, moments, { by = 'packer' } = {}) {
  const lines = moments.map(
    m =>
      '    { id: ' + JSON.stringify(m.id) + ', name: ' + JSON.stringify(m.name) + ', start: ' + m.start + ', dark: ' + (m.tone === 'dark') +
      ', tint: ' + JSON.stringify(m.tint) + ', opacity: ' + m.opacity + ',\n      alt: ' + JSON.stringify(m.alt) + ',\n      svg: ' + JSON.stringify(m.text) + ' },',
  )
  const head =
    by === 'editor'
      ? '// Generated by the BackdropKit editor for the theme ' + theme.name + '. Do not edit: open the\n' +
        "// archive's project.json in the BackdropKit editor and export again to change it. Each scene\n" +
        '// is one animated SVG document, as the app plays it, and each moment lasts from its start hour\n' +
        '// until the next one starts.\n'
      : '// Generated by the BackdropKit packer for the theme ' + theme.name + '. Do not edit: the scenes and the\n' +
        "// words come from the BackdropKit project, and packing again writes this file anew. Each scene\n" +
        '// is one animated SVG document, as the app plays it, and each moment lasts from its start hour\n' +
        '// until the next one starts.\n'
  return head + 'export const THEME = {\n' + '  slug: ' + JSON.stringify(theme.slug) + ',\n' + '  name: ' + JSON.stringify(theme.name) + ',\n' + '  moments: [\n' + lines.join('\n') + '\n' + '  ],\n' + '}\n'
}

export function description(theme, single, { by = 'packer', repo = REPO } = {}) {
  const line = theme.line.replace(/\.\s*$/, '')
  const what = line.charAt(0).toLowerCase() + line.slice(1)
  const how = single ? 'the same at every hour' : 'that follows your clock'
  return `${theme.name}: ${what}, as an animated pixel-art scene behind the conversation ${how}. ${creditOf(by, repo)}`
}

// The README. theme: { slug, name, line, about? } (about: the site catalog's words; the
// editor's themes have none).
export function readme(theme, moments, hooks, { by = 'packer', repo = REPO, heroOrder = HERO_ORDER } = {}) {
  const s = theme.slug
  const single = moments.length === 1
  const credit = creditOf(by, repo)
  const about = (theme.about ?? '').replace(/\s*The same at every hour\.\s*$/, '')
  const list = hooks
    .map(f => {
      const note = HOOK_NOTES[f]?.(s) ?? (f.endsWith('.d.ts') ? 'type declarations for ' + f.replace('.d.ts', '.js') : '')
      return '- `mod/hooks/' + f + '`' + (note ? ': ' + note + '.' : '')
    })
    .join('\n')
  const when = single
    ? `It is the same at every hour: one scene, all day.`
    : `It follows your computer's clock, with one scene for each part of the day:

| Scene | From | To | Panels |
| --- | --- | --- | --- |
${moments.map((m, i) => `| ${m.name} | ${clock(m.start)} | ${clock((moments[i + 1] ?? moments[0]).start)} | ${m.tone} |`).join('\n')}

The scene changes within five minutes of its hour, and the app's panels change with it: light
with dark words over a light scene, dark with pale words over a dark one, the frosted glass
tinted from the scene.`
  const keys = moments.map(m => m.name.toLowerCase().replace(/\s+/g, '-'))
  const use = single
    ? `- \`/${s}-off\` takes the theme off, in new sessions too; \`/${s}-on\` puts it back.
- \`/${s}-time\` says when the scene plays: all day, so there is no other moment to preview.`
    : `- \`/${s}-time\` lists when each scene plays. \`/${s}-time ${keys[keys.length - 1]}\` (or ${keys.slice(0, -1).join(', ')}, or a
  time like 18:30) previews another moment and runs on from it; \`/${s}-time now\` goes back
  to your clock.
- \`/${s}-off\` takes the theme off, in new sessions too; \`/${s}-on\` puts it back.`
  const intro = `A BackdropKit theme for the Claude desktop app: ${theme.line.charAt(0).toLowerCase() + theme.line.slice(1)}` + (by === 'editor' ? (about ? ' ' + about : '') : ' ' + about)
  const projectLine =
    by === 'editor'
      ? "- `project.json`: the theme's project file: open it in the BackdropKit editor to change the theme."
      : "- `project.json`: the theme's project file for the BackdropKit editor (empty for now)."
  return `# ${theme.name}

${intro}

It is an animated pixel-art scene behind your Claude Code conversation, with the app's colours
to match. ${when}

${credit}

## What is inside

- \`.claude-plugin/marketplace.json\`: a marketplace with one plugin, named \`backdropkit-${s}\`.
- \`mod/.claude-plugin/plugin.json\`: the plugin, named \`${s}\`, version ${VERSION}.
${list}
- \`preview.png\`: a still of the ${single ? 'scene' : heroOf(moments, heroOrder).name + ' scene'}.
${projectLine}
- \`README.md\`: this file.

Nothing else belongs in the archive. The plugin reads no files and makes no network requests.

## Install by hand

Unpack the archive into a folder you keep (the theme is read from it), for example
\`~/.claude/backdropkit/${s}\`, then run these two commands with that folder's path:

\`\`\`
claude plugin marketplace add "<that folder>"
claude plugin install ${s}@backdropkit-${s} --scope user
\`\`\`

Run /reload-plugins or start a new session to see the theme. If another theme plugin is on,
turn it off first (\`claude plugin disable <name>\`): the theme set last wins.

## Use

${use}
- To remove it: \`claude plugin uninstall ${s}@backdropkit-${s}\`.

The app plays the motion only with the GPU on and reduced motion off; otherwise it shows a
still frame of the scene.
`
}

// register.tsx with the slug in its six command names (the template holds __SLUG__ there, so
// claude plugin validate reads them as commands the module answers itself).
export function stampRegister(text, slug) {
  const stamps = text.split("'__SLUG__-").length - 1
  if (stamps !== 6) throw new Error(`register.tsx: expected 6 command names to stamp, found ${stamps}`)
  const out = text.replaceAll("'__SLUG__-", "'" + slug + '-')
  if (out.includes('__SLUG__')) throw new Error('register.tsx: a __SLUG__ left after stamping')
  return out
}

const textOf = d => (typeof d === 'string' ? d : new TextDecoder().decode(d))

// The archive's entries, in order: [{ name, data }].
//   theme: { slug, name, line, about? }; moments: as themeJs; hookFiles: { name: text or
//   bytes } of engine/theme-mod/hooks (theme.js is made here); preview: PNG bytes; project:
//   the text of project.json.
export function archiveEntries({ theme, moments, hookFiles, preview, project = '{}\n', by = 'packer', repo = REPO, heroOrder = HERO_ORDER }) {
  const s = theme.slug
  const single = moments.length === 1 && (by === 'editor' || moments[0].id === '')
  const files = { ...hookFiles, 'theme.js': themeJs(theme, moments, { by }) }
  files['register.tsx'] = stampRegister(textOf(files['register.tsx']), s)
  const hooks = Object.keys(files).sort()
  const desc = description(theme, single, { by, repo })
  const author = { name: authorOf(by), url: repo }
  const plugin = { name: s, version: VERSION, description: desc, author, homepage: repo, license: 'MIT' }
  const marketplace = {
    name: 'backdropkit-' + s,
    owner: author,
    metadata: { description: `${theme.name}, a BackdropKit theme for the Claude desktop app. ${creditOf(by, repo)}` },
    plugins: [{ name: s, source: './mod', description: desc, version: VERSION }],
  }
  const entries = [
    { name: '.claude-plugin/marketplace.json', data: JSON.stringify(marketplace, null, 2) + '\n' },
    { name: 'mod/.claude-plugin/plugin.json', data: JSON.stringify(plugin, null, 2) + '\n' },
    ...hooks.map(f => ({ name: 'mod/hooks/' + f, data: files[f] })),
    { name: 'README.md', data: readme(theme, moments, hooks, { by, repo, heroOrder }) },
    { name: 'preview.png', data: preview ?? new Uint8Array(0) },
    { name: 'project.json', data: project },
  ]
  // Nothing local may go in: no absolute Windows or home path.
  for (const e of entries) {
    if (e.name.endsWith('.png')) continue
    const t = textOf(e.data)
    if (/[a-z]:[\\/]+users[\\/]/i.test(t) || /(^|[\s"'(])\/(?:Users|home)\/[^/\s]+\//.test(t)) throw new Error(`${s}: ${e.name} holds a local path`)
  }
  return entries
}

// The install prompt, as on the landing page (site/src/site.js).
export function installPrompt(theme) {
  const S = theme.slug
  return `Install the BackdropKit theme "${theme.name}" for the Claude desktop app.

1. Find ${S}.zip (I just downloaded it, most likely into my Downloads folder).
2. Before installing, list what is inside. It should hold only: .claude-plugin/marketplace.json,
   mod/.claude-plugin/plugin.json, mod/hooks/ (the files listed in README.md), project.json, preview.png,
   README.md. If there is anything else, stop and tell me.
3. Read mod/hooks/register.tsx and tell me in two lines what it does.
4. Unpack it into ~/.claude/backdropkit/${S}, replacing an older copy if there is one.
   Keep this folder: the theme is read from it.
5. Run: claude plugin marketplace add "<that folder>"
   then: claude plugin install ${S}@backdropkit-${S} --scope user
6. If another theme plugin is enabled, ask me before turning it off.
7. Tell me to run /reload-plugins or start a new session to see the theme.`
}
