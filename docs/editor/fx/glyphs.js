// Shades are patterns on the whole grid (they tile seamlessly from block to block).
const SHADES = {
  sh1: (x, y) => (x & 1) === 0 && (y & 1) === 0,
  sh2: (x, y) => (y & 1) === 0,
  sh3: (x, y) => !((x & 1) === 1 && (y & 1) === 1),
  sh4: () => true,
}

export const GLYPH_SIZES = { '5x7': { w: 5, h: 7, i: 0 }, '7x9': { w: 7, h: 9, i: 1 } }

// Glyph cells as [x, y] lists, per size.
const CELLS = {}
for (const id in BITMAPS) {
  CELLS[id] = BITMAPS[id].map((rows, i) => {
    const want = i === 0 ? [5, 7] : [7, 9]
    if (rows.length !== want[1] || rows.some(r => r.length !== want[0])) throw new Error('glyph ' + id + ' is not ' + want.join('x'))
    const out = []
    rows.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === '#') out.push([x, y])
    })
    return out
  })
}

