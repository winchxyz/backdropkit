const RAMPS = {
  ascii: ['sp', 'dot', 'colon', 'dash', 'eq', 'plus', 'star', 'hash', 'pct', 'at'],
  blocks: ['sp', 'sh1', 'sh2', 'sh3', 'sh4'],
  dots: ['sp', 'd1', 'd2', 'd3', 'd4', 'd5', 'd6'],
}
// Afterglyph's "signal" ramp: brightness bands, each with a few glyphs picked at random.
const SIGNAL = [
  ['sp', 'dot', 'sp', 'sp'],
  ['dot', 'dash', 'colon', 'dash'],
  ['dash', 'tilde', 'eq', 'x', 'plus'],
  ['eq', 'root', 'pi', 'delta', 'zero', 'x'],
  ['zero', 'zero', 'ring', '8', 'zero'],
  ['ring', 'eye', 'zero', 'eye'],
  ['eye', 'disc', 'eye', 'disc'],
  ['disc', 'eye', 'disc', 'disc'],
]
const SIGNAL_AT = [0.08, 0.2, 0.32, 0.44, 0.58, 0.74, 0.9]
const DIR_THIN = ['h', 'bs', 'v', 'sl']
const DIR_BOLD = ['hb', 'bsb', 'vb', 'slb']

/**
 * The glyph for a block (Afterglyph's compose):
 *   L: brightness 0..1 (levelled), en: edge energy 0..1, ch: edge coherence 0..1,
 *   q: edge direction 0..3 (horizontal, down-right, vertical, down-left),
 *   hv: a stable random number for the block, set, edges (strokes on strong edges).
 */
export function pickGlyph(L, en, ch, q, hv, set, edges) {
  if (set === 'lines') return L > 0.07 || en > 0.3 ? (L > 0.6 ? DIR_BOLD[q] : DIR_THIN[q]) : 'sp'
  if (edges && en > 0.5 && ch > 0.42 && L > 0.05) return DIR_BOLD[q]
  if (edges && en > 0.2 && ch > 0.45 && L < 0.8 && L > 0.05) return DIR_THIN[q]
  if (set === 'digits' || set === 'binary') {
    if (L <= 0.06) return 'sp'
    const list = set === 'binary' ? ['0', '1'] : DIGITS
    return list[((hv * 977) % 1) * list.length | 0]
  }
  if (set in RAMPS) {
    const ramp = RAMPS[set]
    const Lr = Math.min(0.9999, Math.max(0, L + (hv - 0.5) * 0.06))
    return ramp[(Lr * ramp.length) | 0]
  }
  // signal
  const Lr = L + (hv - 0.5) * 0.14
  let k = 0
  while (k < 7 && Lr >= SIGNAL_AT[k]) k++
  const R = SIGNAL[k]
  return R[((hv * 977) % 1) * R.length | 0]
}

// Calls put(x, y) for every ink cell of glyph `id` drawn with its block's top-left at (bx, by).
export function drawGlyph(id, size, bx, by, put) {
  const sz = GLYPH_SIZES[size] ?? GLYPH_SIZES['5x7']
  const shade = SHADES[id]
  if (shade) {
    for (let y = 0; y < sz.h; y++) for (let x = 0; x < sz.w; x++) if (shade(bx + x, by + y)) put(bx + x, by + y)
    return
  }
  const cells = CELLS[id]?.[sz.i]
  if (!cells) return
  for (const [x, y] of cells) put(bx + x, by + y)
}

// How much of a glyph's block it inks (0..1), for tests and for ordering ramps.
export function glyphInk(id, size) {
  const sz = GLYPH_SIZES[size] ?? GLYPH_SIZES['5x7']
  let n = 0
  drawGlyph(id, size, 0, 0, () => n++)
  return n / (sz.w * sz.h)
}
